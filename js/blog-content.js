// Function to render blog content based on language
function renderBlogContent(blogId, lang) {
  const content = blogContent[blogId];
  if (!content || !content[lang]) {
    console.error(`Blog content not found for ${blogId} in ${lang}`);
    return;
  }

  const data = content[lang];

  // Update category
  const categoryEl = document.querySelector(".blog-detail-category");
  if (categoryEl) categoryEl.textContent = data.category;

  // Update title
  const titleEl = document.querySelector(".blog-detail-title");
  if (titleEl) titleEl.textContent = data.title;

  // Update meta information
  const metaSpans = document.querySelectorAll(".blog-detail-meta span");
  if (metaSpans[0])
    metaSpans[0].innerHTML = `<i class="bx bx-calendar"></i> ${data.date}`;
  if (metaSpans[1])
    metaSpans[1].innerHTML = `<i class="bx bx-time"></i> ${data.readTime}`;
  if (metaSpans[2])
    metaSpans[2].innerHTML = `<i class="bx bx-user"></i> ${data.author}`;

  // Update image
  const imgEl = document.querySelector(".blog-detail-image img");
  if (imgEl) {
    imgEl.src = data.image;
    imgEl.alt = data.imageAlt;
  }

  // Update lead paragraph
  const leadEl = document.querySelector(".blog-detail-content .lead");
  if (leadEl) leadEl.textContent = data.lead;

  // Update sections
  const contentEl = document.querySelector(".blog-detail-content");
  if (contentEl && data.sections) {
    // Remove existing h2 and p elements after lead
    const elementsToRemove = contentEl.querySelectorAll("h2, p:not(.lead)");
    elementsToRemove.forEach((el) => el.remove());

    // Find the CTA element to insert before it
    const ctaEl = contentEl.querySelector(".blog-cta");

    // Add new sections
    data.sections.forEach((section) => {
      const h2 = document.createElement("h2");
      h2.textContent = section.heading;

      if (ctaEl) {
        contentEl.insertBefore(h2, ctaEl);
      } else {
        contentEl.appendChild(h2);
      }

      if (section.content.includes("<p>")) {
        // Content contains HTML
        const div = document.createElement("div");
        div.innerHTML = section.content;
        const paragraphs = div.querySelectorAll("p");
        paragraphs.forEach((p) => {
          if (ctaEl) {
            contentEl.insertBefore(p, ctaEl);
          } else {
            contentEl.appendChild(p);
          }
        });
      } else {
        // Simple text content
        const p = document.createElement("p");
        p.textContent = section.content;
        if (ctaEl) {
          contentEl.insertBefore(p, ctaEl);
        } else {
          contentEl.appendChild(p);
        }
      }
    });
  }

  // Update CTA
  const ctaTitleEl = document.querySelector(".blog-cta h3");
  if (ctaTitleEl) ctaTitleEl.textContent = data.ctaTitle;

  const ctaTextEl = document.querySelector(".blog-cta p");
  if (ctaTextEl) ctaTextEl.textContent = data.ctaText;

  const ctaButtonEl = document.querySelector(".cta-button");
  if (ctaButtonEl) ctaButtonEl.textContent = data.ctaButton;

  // Update tags
  const tagsContainer = document.querySelector(".blog-detail-tags");
  if (tagsContainer && data.tags) {
    // Remove existing tags except label
    const existingTags = tagsContainer.querySelectorAll(".blog-tag");
    existingTags.forEach((tag) => tag.remove());

    // Add new tags
    data.tags.forEach((tag) => {
      const span = document.createElement("span");
      span.className = "blog-tag";
      span.textContent = tag;
      tagsContainer.appendChild(span);
    });
  }
}

// Initialize blog content on page load
document.addEventListener("DOMContentLoaded", () => {
  // Get blog ID from URL
  const path = window.location.pathname;
  const blogId = path.split("/").pop().replace(".html", "");

  // Get current language
  const currentLang = localStorage.getItem("language") || "ar";

  // Render blog content
  if (blogContent[blogId]) {
    renderBlogContent(blogId, currentLang);
  }

  // Listen for language changes
  window.addEventListener("languageChanged", (e) => {
    const newLang = e.detail.language;
    if (blogContent[blogId]) {
      renderBlogContent(blogId, newLang);
    }
  });
});

// Function to render service content
function renderServiceContent(serviceId, lang) {
  const content = serviceContent[serviceId][lang];
  if (!content) {
    console.error(
      `Content not found for service: ${serviceId}, language: ${lang}`,
    );
    return;
  }

  const container = document.getElementById("service-content");
  if (!container) {
    console.error("Container element #service-content not found");
    return;
  }

  let html = `
    <a href="../services.html" class="back-button">
      ${content.backButton}
    </a>
    
    <div class="service-hero">
      <span class="service-category">${content.category}</span>
      <h1>${content.title}</h1>
      <p class="service-hero-lead">${content.lead}</p>
      <div class="service-hero-image">
        <img src="${content.image}" alt="${content.imageAlt}" loading="eager" />
      </div>
    </div>
  `;

  // Add sections
  content.sections.forEach((section) => {
    html += `
      <div class="service-content">
        <h2>${section.title}</h2>
        ${section.content}
      </div>
    `;
  });

  // Add CTA
  html += `
    <div class="service-cta">
      <h2>${content.ctaTitle}</h2>
      <p>${content.ctaText}</p>
      <a href="https://wa.me/201002507882" class="service-cta-button" target="_blank">
        <i class='bx bxl-whatsapp'></i>
        ${content.ctaButton}
      </a>
    </div>
  `;

  container.innerHTML = html;

  // Update page title and meta description
  document.title = content.title;
  const metaDesc = document.querySelector('meta[name="description"]');
  if (metaDesc) {
    metaDesc.setAttribute("content", content.lead);
  }

  // Update html lang and dir attributes
  document.documentElement.lang = lang === "ar" ? "ar" : "en";
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";

  // Initialize FAQ toggle functionality
  initializeFAQToggle();
}

// FAQ Toggle Functionality
function initializeFAQToggle() {
  const faqQuestions = document.querySelectorAll(".faq-question");

  faqQuestions.forEach((question) => {
    question.addEventListener("click", function () {
      const faqItem = this.parentElement;
      const answer = faqItem.querySelector(".faq-answer");
      const icon = this.querySelector("i");

      // Check if currently open
      const isOpen = answer.style.display === "block";

      // Close all other FAQs
      document.querySelectorAll(".faq-answer").forEach((ans) => {
        ans.style.display = "none";
      });
      document.querySelectorAll(".faq-question i").forEach((ic) => {
        ic.style.transform = "rotate(0deg)";
      });

      // Toggle current FAQ
      if (!isOpen) {
        answer.style.display = "block";
        icon.style.transform = "rotate(180deg)";
      }
    });
  });
}

// Initialize on page load
document.addEventListener("DOMContentLoaded", function () {
  // Get service ID from URL
  const path = window.location.pathname;
  const serviceId = path.substring(
    path.lastIndexOf("/") + 1,
    path.lastIndexOf("."),
  );

  // Get current language from localStorage
  const currentLang = localStorage.getItem("language") || "ar";

  // Render content
  renderServiceContent(serviceId, currentLang);
});

// Listen for language changes
window.addEventListener("languageChanged", function (e) {
  const path = window.location.pathname;
  const serviceId = path.substring(
    path.lastIndexOf("/") + 1,
    path.lastIndexOf("."),
  );
  renderServiceContent(serviceId, e.detail.language);
});
